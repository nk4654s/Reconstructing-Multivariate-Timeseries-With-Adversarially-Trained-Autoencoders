"""This module contains a custom sampler, which returns indicies concerning the within a given range."""
from torch.utils.data import Sampler
import numpy as np


class RandomBatchSampler(Sampler):
    """
    A custom sampler that generates random batches of indices from a dataset.

    Args:
        data_length (int): The length of the dataset, which results in the highest index
            to be returned by the sampler.
        batch_size (int): The size of each batch that will be generated by the sampler.
        shuffle (bool): Whether or not to randomly permutate the indicies.
    """

    def __init__(
        self,
        data_length: int,
        batch_size: int,
        shuffle: bool = True,
    ):
        super().__init__()

        self._data_length = data_length
        self._batch_size = batch_size

        # randomly permutate the indicies if shuffle is set to true, otherwise
        # use the indicies sequentially
        if shuffle:
            self._indicies = np.random.permutation(self._data_length).tolist()
        else:
            self._indicies = [_ for _ in range(data_length)]


    def __iter__(self):
        for i in range(0, len(self._indicies), self._batch_size):
            yield self._indicies[i : i + self._batch_size]

    def __len__(self):
        return len(self._indicies) // self._batch_size
